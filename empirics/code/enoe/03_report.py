"""Write empirics/output/enoe/results.md from the aggregate tables of 02_flows.py.

    python empirics/code/enoe/03_report.py

Generated; do not edit by hand. Interpretation is in papers/WP09_job_ladders_mexico/.
"""
import pandas as pd

from enoe_config import OUTPUT

LABEL = {"exit_y": "exit to non-employment within a year", "up_y": "upward transition within a year (any)",
         "up_emp_y": "upward transition within a year with a change of employer"}


def main():
    ld = pd.read_csv(OUTPUT / "link_diagnostics.csv")
    q = pd.read_csv(OUTPUT / "quarterly_rates.csv")
    dec = pd.read_csv(OUTPUT / "decomposition.csv")
    st = pd.read_csv(OUTPUT / "sector_test.csv")
    mis = pd.read_csv(OUTPUT / "misreport.csv") if (OUTPUT / "misreport.csv").exists() else pd.DataFrame()
    L = ["# ENOE job ladders: results", "",
         "*Generated by `empirics/code/enoe/03_report.py`; do not edit by hand. Design: "
         "`papers/WP09_job_ladders_mexico/00_pre_analysis_plan.md` (D-046 to D-048). Ages 16–65; "
         "pre = 2018Q4–2019Q4, post = 2023Q1–2024Q1; weights: origin-quarter FAC_TRI.*", "",
         "## 1. Linking", "", "| Window | From | Eligible | Linked | Match rate | Key |", "|---|---|---|---|---|---|"]
    for _, r in ld.iterrows():
        L.append(f"| {r.window} | {r.quarter_from} | {r.eligible:,} | {r.accepted:,} | {r.match_rate:.3f} | {r.key} |")
    L += ["", "## 2. Quarterly flows (average over the window's four pairs)", "",
          "| Window | Area | Employment exit | Job finding | Job-to-job (Q4→Q1 only) |", "|---|---|---|---|---|"]
    for (w, a), g in q.groupby(["window", "area"], sort=False):
        L.append(f"| {w} | {a} | {g.exit_rate.mean():.3f} | {g.job_finding_rate.mean():.3f} | "
                 f"{g.job_to_job_rate.dropna().mean():.3f} |")
    L += ["", "## 3. Sector vs size × formality: Shapley shares of R²", "",
          "| Window | Outcome | Variant | n | Sector | Size × formality | Difference [90% interval] |",
          "|---|---|---|---|---|---|---|"]
    for _, r in dec.iterrows():
        L.append(f"| {r.window} | {LABEL.get(r.outcome, r.outcome)} | {r.variant} | {int(r.n):,} | {r.shapley_sector:.4f} | "
                 f"{r.shapley_sizeform:.4f} | {r['diff']:+.4f} [{r.diff_lo90:+.4f}, {r.diff_hi90:+.4f}] |")
    L += ["", "## 4. Manufacturing minus services within size × formality cells", "",
          "Controls: size × formality, age group, sex, schooling level. Services: rama_est2 5–10.", "",
          "| Window | Outcome | n | Services mean | Manufacturing − services [90% interval] |", "|---|---|---|---|---|"]
    for _, r in st.iterrows():
        L.append(f"| {r.window} | {LABEL.get(r.outcome, r.outcome)} | {int(r.n):,} | {r.mean_services:.3f} | "
                 f"{r.manufacturing_minus_services:+.4f} [{r.lo90:+.4f}, {r.hi90:+.4f}] |")
    if len(mis):
        L += ["", "## 5. Same employer, different answers (two first-quarter visits a year apart)", "",
              "| Window | n | Size class differs | Formality differs |", "|---|---|---|---|"]
        for _, r in mis.iterrows():
            L.append(f"| {r.window} | {int(r.n):,} | {r.size_changes:.3f} | {r.formality_changes:.3f} |")
    L += ["", "Rates by sector, by size × formality and by job cell are in `rates_*.csv`."]
    (OUTPUT / "results.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
