import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from enoe_config import OUTPUT_ROOT  # noqa: E402

OUT = OUTPUT_ROOT / "productivity_ladder"


def main():
    v = pd.read_csv(OUT / "verdicts.csv")
    d = pd.read_csv(OUT / "decomposition.csv")
    s = pd.read_csv(OUT / "segments.csv")
    periods = list(dict.fromkeys(v["period"]))
    L = ["# A productivity ladder for Mexico with formal and informal steps: results", "",
         "*Generated by `empirics/code/enoe/productivity_ladder/03_report.py`; do not edit by hand. Design: "
         "`papers/WP09_jobs_mexico/9.3_productivity_ladder/00_pre_analysis_plan.md` (D-052). ENOE annual averages of "
         "four quarters; UN sector value added at initial- and final-year prices; population aged 15+.*", "",
         "## 1. Verdicts (both price bases must agree)", "", "| Specification | " + " | ".join(periods) + " |",
         "|---" * (len(periods) + 1) + "|"]
    vi = v[v["base"] == "initial"]
    for spec, g in vi.groupby("spec", sort=False):
        g = g.set_index("period")
        L.append(f"| {spec} | " + " | ".join(g.loc[p, "verdict"] for p in periods) + " |")
    L += ["", "## 2. Decomposition of output per worker (percentage points a year, initial-year prices)", "",
          "| Period | Specification | Growth | Within | Between sectors | Between segments within sectors | Employment rate (log) |",
          "|---|---|---|---|---|---|---|"]
    for _, r in d.iterrows():
        L.append(f"| {r.period} | {r.spec} | {r.growth_pp:+.3f} | {r.within_pp:+.3f} | {r.between_sector_pp:+.3f} | "
                 f"{r.between_within_sector_pp:+.3f} | {r.emprate_log_pp:+.3f} |")
    m = s[s["formality"] == "informal"].pivot(index="sector", columns="year", values="informal_share")
    rr = s[s["formality"] == "informal"].pivot(index="sector", columns="year", values="informal_formal_ratio")
    L += ["", "## 3. Informal share of sector employment", "", "| Sector | " + " | ".join(map(str, m.columns)) + " |",
          "|---" * (len(m.columns) + 1) + "|"]
    L += [f"| {i} | " + " | ".join(f"{x:.3f}" for x in r) + " |" for i, r in m.iterrows()]
    L += ["", "## 4. Informal / formal mean monthly labour income within sectors", "",
          "| Sector | " + " | ".join(map(str, rr.columns)) + " |", "|---" * (len(rr.columns) + 1) + "|"]
    L += [f"| {i} | " + " | ".join(f"{x:.3f}" for x in r) + " |" for i, r in rr.iterrows()]
    (OUT / "results.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
