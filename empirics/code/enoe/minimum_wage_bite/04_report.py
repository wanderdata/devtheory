"""Study 9.8, step 4: results report (empirics/output/enoe/minimum_wage_bite/results.md).

    python empirics/code/enoe/minimum_wage_bite/04_report.py
"""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[4]
OUT = ROOT / "empirics" / "output" / "enoe" / "minimum_wage_bite"


def md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v) for v in r.values) + " |")
    return "\n".join(lines)


def f3(x):
    return "" if pd.isna(x) else f"{x:.3f}"


def main():
    est = pd.read_csv(OUT / "estimates.csv")
    ev = pd.read_csv(OUT / "event.csv")
    tests = pd.read_csv(OUT / "tests.csv")
    rob = pd.read_csv(OUT / "robustness.csv")
    bite = pd.read_csv(OUT / "bite.csv")
    imp = pd.read_csv(OUT / "implied_productivity.csv")
    m = bite[bite["n18"] >= 100]
    L = ["# Study 9.8 — Minimum-wage increases of 2019–2024 by state and activity: generated results\n",
         "*Generated by `empirics/code/enoe/minimum_wage_bite/04_report.py`; do not edit by hand. Cells: 31 units "
         "(Mexico City and the State of Mexico combined) × 20 activity groups, non-oil, with at least 100 full-time "
         "wage employees with reported income in 2018. Treatment: 2018 bite (share of those workers below the 2019 "
         "minimum). Model: cell, state × year and activity × year effects; weights 2018 employment; clustered by "
         "state. Coefficients are per unit of bite (0 to 1). Post estimand: mean of the 2022–2024 coefficients, "
         "relative to 2018.*\n",
         "## 1. Treatment\n",
         f"Cells: {len(m)}. Bite: mean {m['bite18'].mean():.3f}, median {m['bite18'].median():.3f}, interquartile range "
         f"{m['bite18'].quantile(.25):.3f} to {m['bite18'].quantile(.75):.3f}, maximum {m['bite18'].max():.3f}. "
         f"Correlation with the 2017 bite {m[['bite18', 'bite17']].corr().iloc[0, 1]:.2f}, with the Kaitz index "
         f"{m[['bite18', 'kaitz']].corr().iloc[0, 1]:.2f}, with the formal-only bite "
         f"{m[['bite18', 'bite18_formal']].corr().iloc[0, 1]:.2f}.\n",
         "## 2. Estimates\n"]
    t = pd.DataFrame({"Outcome": est["label"], "Post (2022–2024)": est["post"].map(f3),
                      "90% interval (wild)": [f"{f3(a)} to {f3(b)}" for a, b in zip(est["lo90"], est["hi90"])],
                      "2019": est["b2019"].map(f3), "Pre-trend p (2015–2017)": est["p_pretrend"].map(f3),
                      "Cells": est["cells"]})
    L.append(md(t) + "\n")
    L.append("## 3. Event-study coefficients (CR1 standard errors in parentheses)\n")
    p = ev.pivot(index="year", columns="outcome", values="beta")
    s = ev.pivot(index="year", columns="outcome", values="se")
    cols = ["w_all", "w_formal", "w_informal", "lemp", "formal", "lprod"]
    tab = pd.DataFrame({"Year": p.index})
    for c in cols:
        tab[c] = [f"{p.loc[y, c]:.3f} ({s.loc[y, c]:.3f})" for y in p.index]
    L.append(md(tab) + "\n")
    L.append("## 4. Tests\n")
    tt = pd.DataFrame({"Proposition": tests["proposition"], "Outcome": tests["outcome"],
                       "Post": tests["post"].map(f3),
                       "90% interval": [f"{f3(a)} to {f3(b)}" for a, b in zip(tests["lo90"], tests["hi90"])],
                       "Pre-trend p": tests["p_pretrend"].map(f3), "Ratio to first stage":
                           tests["ratio_to_first_stage"].map(f3), "Verdict": tests["verdict"]})
    L.append(md(tt) + "\n")
    L.append(f"First stage (mean log hourly wage of wage employees): {tests['first_stage'].iloc[0]:.3f}.\n")
    L.append("## 5. Robustness (CR1 90% intervals)\n")
    r = rob.copy()
    r["est"] = [f"{f3(a)} ({f3(b)} to {f3(c)}); ratio {f3(d)}" for a, b, c, d in
                zip(r["post"], r["lo_cr1"], r["hi_cr1"], r["ratio_to_first_stage"])]
    w = r.pivot(index="specification", columns="outcome", values="est").reindex(r["specification"].unique())
    w = w[["w_all", "lemp", "formal", "lprod", "w_informal"]].reset_index()
    L.append(md(w) + "\n")
    L.append("## 6. Implied effect on state productivity relative to the least-exposed cells (illustration)\n")
    L.append(f"Combining the post estimates for employment and value added per worker, the implied effect on state "
             f"non-oil productivity, relative to a counterfactual in which every cell behaved like a cell with zero "
             f"bite, has a median across units of {100 * imp['implied_log_effect'].median():.2f} log points and ranges "
             f"from {100 * imp['implied_log_effect'].min():.2f} to {100 * imp['implied_log_effect'].max():.2f}.\n")
    dg = OUT / "diagnostics.csv"
    if dg.exists():
        g = pd.read_csv(dg)
        L.append("## 7. Diagnostics added after the main estimates (D-069)\n")
        L.append(md(pd.DataFrame({"Specification": g["specification"], "Outcome": g["outcome"],
                                  "Post": g["post"].map(f3),
                                  "90% interval (wild)": [f"{f3(a)} to {f3(b)}" for a, b in zip(g["lo90"], g["hi90"])],
                                  "Pre-trend p": g["p_pretrend"].map(f3),
                                  "Mean 2015–2017 coefficient": g["mean_pre_2015_2017"].map(f3),
                                  "Post minus pre": g["post_minus_pre"].map(f3)})) + "\n")
    (OUT / "results.md").write_text("\n".join(L), encoding="utf-8")
    print("written", OUT / "results.md")


if __name__ == "__main__":
    main()
