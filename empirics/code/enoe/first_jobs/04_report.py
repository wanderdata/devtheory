"""Study 9.5, step 4: results.md, applying the decision rules of the pre-analysis plan (§1).

    python empirics/code/enoe/first_jobs/04_report.py
"""
import importlib
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE.parent))

import pandas as pd  # noqa: E402

ex = importlib.import_module("01_extract")
OUT = ex.OUT


def table(df, cols):
    out = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    for _, r in df.iterrows():
        out += "| " + " | ".join(str(r[c]) for c in cols) + " |\n"
    return out


def judge(est, checks):
    m = est[est["spec"] == "main"].set_index("proposition")
    out = {}
    gap = checks["informal share of first jobs"] - checks["informal share of stock 15-24"]
    out["P34"] = ("supported" if gap >= 0.10 else "rejected" if gap < 0.03 else "inconclusive",
                  f"informal share of first jobs {checks['informal share of first jobs']:.3f} against "
                  f"{checks['informal share of stock 15-24']:.3f} among all employed 15-24 (difference {gap:+.3f})")
    r = m.loc["P35"]
    out["P35"] = ("supported" if r["lo90"] > 0 else "rejected (trap)" if r["hi90"] < 0 else "inconclusive",
                  f"{r['beta']:+.4f} [{r['lo90']:+.4f}, {r['hi90']:+.4f}]; formal at interview 5 among those still not "
                  f"employed at 2: {r['mean_control']:.4f}")
    r = m.loc["P36"]
    out["P36"] = ("supported" if r["lo90"] >= 0.25 else "rejected" if r["hi90"] < 0.25 else "inconclusive",
                  f"{r['beta']:+.4f} [{r['lo90']:+.4f}, {r['hi90']:+.4f}]; formal at interview 5 among informal entrants: "
                  f"{r['mean_control']:.4f}")
    r = m.loc["P37"]
    out["P37"] = ("supported" if (r["beta"] >= 0.10 and r["lo90"] > 0) else "rejected" if r["hi90"] < 0.10 else "inconclusive",
                  f"{r['beta']:+.4f} [{r['lo90']:+.4f}, {r['hi90']:+.4f}]; formal at interview 5 among informal "
                  f"own-account or unpaid entrants: {r['mean_control']:.4f}")
    return out


def main():
    est = pd.read_csv(OUT / "estimates.csv")
    checks = pd.read_csv(OUT / "checks.csv", index_col=0)["value"].astype(float)
    j = judge(est, checks)
    txt = ["# Study 9.5 — results (generated; do not edit)\n",
           "Generated by `empirics/code/enoe/first_jobs/04_report.py`. Plan: "
           "`papers/WP09_jobs_mexico/9.5_first_jobs/00_pre_analysis_plan.md`.\n", "## Propositions\n"]
    for k, (v, why) in j.items():
        txt.append(f"- **{k}: {v}.** {why}.")
    txt.append("\n## Checks and sample\n")
    txt.append(table(checks.reset_index().assign(value=lambda d: d["value"].map(lambda x: f"{x:,.4g}")), ["check", "value"]))
    txt.append("\n## Estimates (effect on formal employment at interview 5)\n")
    e = est.copy()
    for c in ["beta", "lo90", "hi90", "mean_control"]:
        e[c] = e[c].map(lambda x: "" if pd.isna(x) else f"{x:+.4f}" if c != "mean_control" else f"{x:.4f}")
    e["n"] = e["n"].map(lambda x: "" if pd.isna(x) else f"{int(x):,}")
    e["n_treated"] = e["n_treated"].map(lambda x: "" if pd.isna(x) else f"{int(x):,}")
    txt.append(table(e.sort_values(["proposition", "spec"]), ["proposition", "spec", "beta", "lo90", "hi90", "mean_control", "n",
                                                             "n_treated"]))
    o = pd.read_csv(OUT / "oster.csv")
    txt.append("\n## Sensitivity to selection on unobservables (Oster)\n")
    txt.append(table(o.round(4), list(o.columns)))
    comp = pd.read_csv(OUT / "composition.csv")
    txt.append("\n## First jobs against all jobs of employed 15-24-year-olds\n")
    txt.append(table(comp.assign(first_jobs=comp["first_jobs"].map(lambda x: f"{x:.3f}"),
                                 stock=comp["stock"].map(lambda x: "" if pd.isna(x) else f"{x:.3f}")),
                     ["dimension", "category", "first_jobs", "stock"]))
    tr = pd.read_csv(OUT / "transitions.csv")
    t5 = tr[tr["interview"] == 5].pivot(index="entry", columns="state", values="share").round(3).reset_index()
    txt.append("\n## State at interview 5 by type of entry at interview 2\n")
    txt.append(table(t5, list(t5.columns)))
    er = pd.read_csv(OUT / "earnings.csv").round(3)
    txt.append("\n## Earnings of first jobs (multiples of the minimum wage in force)\n")
    txt.append(table(er, list(er.columns)))
    (OUT / "results.md").write_text("\n".join(txt) + "\n")
    print("\n".join(txt[:8]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
