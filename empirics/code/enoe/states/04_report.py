"""Study 9.6, step 4: results.md, applying the decision rules of the pre-analysis plan (§1), plus a
leave-one-state-out check of P40 (added after the plan, D-061).

    python empirics/code/enoe/states/04_report.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve()
sys.path.insert(0, str(HERE.parents[1]))
sys.path.insert(0, str(HERE.parent))

import pandas as pd  # noqa: E402
from scipy import stats  # noqa: E402

from enoe_config import OUTPUT_ROOT  # noqa: E402

OUT = OUTPUT_ROOT / "states"
OIL = [4, 27]


def table(df, cols):
    out = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols) + "\n"
    for _, r in df.iterrows():
        out += "| " + " | ".join(str(r[c]) for c in cols) + " |\n"
    return out


def main():
    sig = pd.read_csv(OUT / "signal.csv")
    gr = pd.read_csv(OUT / "growth.csv")
    st = pd.read_csv(OUT / "state_table.csv")
    s1 = sig[(sig["measure"] == "M1") & (sig["period"] == "2005-2011") & (sig["kind"] == "adjusted")].iloc[0]
    v38 = "supported" if s1["signal_share"] >= 0.5 else "rejected" if s1["signal_share"] < 0.2 else "inconclusive"
    p = sig[(sig["measure"] == "M1") & (sig["period"] == "2005-2011 vs 2012-2018")].iloc[0]
    v39 = "supported" if p["disattenuated"] >= 0.5 else "rejected" if p["disattenuated"] < 0.2 else "inconclusive"
    t = gr[gr["role"] == "P40"].iloc[0]
    v40 = "supported" if t["lo90"] > 0 else "rejected" if t["hi90"] < 0 else "inconclusive"
    no = st[~st["ent"].isin(OIL)].reset_index(drop=True)
    loo = [stats.spearmanr(no.drop(i)["M1_2005-2011"], no.drop(i)["g_2012_2019"])[0] for i in range(len(no))]
    txt = ["# Study 9.6 — results (generated; do not edit)\n",
           "Generated by `empirics/code/enoe/states/04_report.py`. Plan: "
           "`papers/WP09_jobs_mexico/9.6_states/00_pre_analysis_plan.md`.\n", "## Propositions\n",
           f"- **P38: {v38}.** Signal share of the variance of adjusted state informal-to-formal rates, 2005-2011: "
           f"{s1['signal_share']:.3f} (variance of estimates {s1['var_estimates']:.6f}, mean sampling variance "
           f"{s1['mean_sampling_var']:.6f}).",
           f"- **P39: {v39}.** Correlation 2005-2011 vs 2012-2018 {p['corr']:.3f} (90% interval {p['corr_lo90']:.3f} to "
           f"{p['corr_hi90']:.3f}); disattenuated {p['disattenuated']:.3f}.",
           f"- **P40: {v40}.** Spearman {t['rho']:.3f} (90% interval {t['lo90']:.3f} to {t['hi90']:.3f}), {int(t['states'])} "
           f"states. Leaving out one state at a time (added after the plan): {min(loo):.3f} to {max(loo):.3f}.\n",
           "## Signal and persistence\n"]
    s = sig.copy()
    for c in s.columns[3:]:
        s[c] = s[c].map(lambda x: "" if pd.isna(x) else f"{x:.4g}")
    txt.append(table(s, list(s.columns)))
    txt.append("\n## Growth\n")
    g = gr.copy()
    for c in ["rho", "lo90", "hi90"]:
        g[c] = g[c].map(lambda x: f"{x:+.3f}")
    txt.append(table(g, ["test", "role", "states", "rho", "lo90", "hi90"]))
    txt.append("\n## States (adjusted one-year rates; growth of GDP per person, log points a year)\n")
    cols = ["state", "M1_2005-2011", "M1_2012-2018", "M1_2022-2025", "M2_2005-2011", "M3_2005-2011", "g_2012_2019",
            "formal_2005_2011"]
    x = st[cols].sort_values("M1_2005-2011", ascending=False).copy()
    for c in cols[1:]:
        x[c] = x[c].map(lambda v: f"{v:.3f}")
    txt.append(table(x, cols))
    (OUT / "results.md").write_text("\n".join(txt) + "\n")
    print("\n".join(txt[:7]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
