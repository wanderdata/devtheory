"""Study 9.2: write empirics/output/enoe/profiles/results.md from the aggregate tables.

    python empirics/code/enoe/profiles/05_report.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd  # noqa: E402

from enoe_config import OUTPUT_ROOT  # noqa: E402

OUT = OUTPUT_ROOT / "profiles"


def md(df):
    """Markdown table without optional dependencies."""
    cols = [str(df.index.name or "")] + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|---" * len(cols) + "|"]
    for i, r in df.iterrows():
        lines.append("| " + " | ".join([str(i)] + [f"{v:.3f}" if isinstance(v, float) else str(v) for v in r]) + " |")
    return "\n".join(lines)


def main():
    h = pd.read_csv(OUT / "heights.csv")
    ph = pd.read_csv(OUT / "panel_heights.csv")
    comp = pd.read_csv(OUT / "composition.csv")
    dg = pd.read_csv(OUT / "diagnostics.csv")
    nr = pd.read_csv(OUT / "nonresponse.csv")
    L = ["# Experience-earnings profiles by type of job: results", "",
         "*Generated by `empirics/code/enoe/profiles/05_report.py`; do not edit by hand. Design: "
         "`papers/WP09_jobs_mexico/9.2_experience_profiles/00_pre_analysis_plan.md` (D-050, D-051). ENOE first "
         "quarters 2005-2025; baseline: men, full-time, private-sector wage employees, 0-40 years of potential "
         "experience. Height = earnings at 20-24 years of experience relative to 0-4 years.*", "",
         "## 1. Height at 20-24 years", "", "| Group | Method | Height | 90% interval | n |", "|---|---|---|---|---|"]
    for _, r in h.iterrows():
        ci = "" if pd.isna(r.lo90) else f"[{r.lo90:.3f}, {r.hi90:.3f}]"
        L.append(f"| {r.group} | {r.method} | {r.height:.3f} | {ci} | {int(r.n):,} |")
    L += ["", "## 2. Within-person synthetic profiles (panels of study 9.1)", "",
          "| Window | Group | n | Height | 90% interval | Flat-spot annual growth |", "|---|---|---|---|---|---|"]
    for _, r in ph.iterrows():
        L.append(f"| {r.window} | {r.group} | {int(r.n):,} | {r.height:.3f} | [{r.lo90:.3f}, {r.hi90:.3f}] | {r.flat_spot_growth:.3f} |")
    L += ["", "## 3. Composition decomposition (log points)", "", md(comp.set_index("method").T), "",
          "## 4. Exploratory diagnostics (not in the plan)", "", "| Analysis | Group | Height | n |", "|---|---|---|---|"]
    for _, r in dg.iterrows():
        L.append(f"| {r.analysis} ({r.period}) | {r.group} | {r.height_20_24:.3f} | {int(r.n):,} |")
    t = nr[nr["year"] != "all"].pivot_table(index="year", columns="formality", values="share_reporting")
    L += ["", "## 5. Share of the baseline sample reporting positive hourly earnings", "", md(t.round(2))]
    (OUT / "results.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
