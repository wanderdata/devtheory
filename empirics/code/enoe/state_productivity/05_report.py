"""Study 9.7, step 5: tables and results report (empirics/output/enoe/state_productivity/results.md).

    python empirics/code/enoe/state_productivity/05_report.py
"""
import importlib.util
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve()
sys.path.insert(0, str(HERE.parent))
_s = importlib.util.spec_from_file_location("est97", HERE.parent / "03_estimates.py")
est = importlib.util.module_from_spec(_s)
_s.loader.exec_module(est)
_g = importlib.util.spec_from_file_location("gdp97", HERE.parents[1] / "states" / "gdp.py")
gdp = importlib.util.module_from_spec(_g)
_g.loader.exec_module(gdp)

OUT, TMP = est.OUT, est.TMP
NAME = {k: v.replace(" de Zaragoza", "").replace(" de Ocampo", "").replace(" de Ignacio de la Llave", "")
        for k, v in gdp.STATES.items()}
NAME[9] = "Mexico City and State of Mexico"


def pct(x, d=2):
    return "" if pd.isna(x) else f"{100 * x:.{d}f}"


def md(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(v).replace("|", "\\|") for v in r.values) + " |")
    return "\n".join(lines)


def main():
    dec = pd.read_csv(OUT / "decomposition_units.csv")
    nat = pd.read_csv(OUT / "national.csv").iloc[0]
    t12 = pd.read_csv(OUT / "tests_p41_p42.csv").set_index("proposition")
    t3 = pd.read_csv(OUT / "tests_p43.csv").iloc[0]
    rob = pd.read_csv(OUT / "robustness.csv")
    con = pd.read_csv(OUT / "national_contributions.csv")
    det = pd.read_csv(OUT / "unit_group_detail.csv")
    d2 = pd.read_csv(OUT / "decomposition_units_2017_2024.csv")
    checks = pd.read_csv(OUT / "panel_checks.csv")
    L = []
    L.append("# Study 9.7 — Labour productivity growth by state and activity: generated results\n")
    L.append("*Generated by `empirics/code/enoe/state_productivity/05_report.py`; do not edit by hand. Growth rates "
             "and decomposition terms are in log points a year (×100), between the averages of 2005–2007 (P0) and "
             "2017–2019 (P1), for the non-oil economy, value added at constant 2018 prices per employed person aged "
             "15+, 31 units (Mexico City and the State of Mexico combined), 20 activity groups. Intervals are 90% "
             "percentile intervals over 199 bootstrap replications of ENOE primary sampling units within state and "
             "period; PIBE and MEITEF are treated as fixed.*\n")
    L.append("## 1. National\n")
    L.append(f"Non-oil labour productivity grew by {pct(nat['national_growth'])} log points a year. Within activities: "
             f"{pct(nat['within'])}; static reallocation: {pct(nat['static'])}; dynamic reallocation: "
             f"{pct(nat['dynamic'])}. At segment level, within segments: {pct(nat['within_seg'])}; formalisation "
             f"term: {pct(nat['formalisation'])}. Formal share of non-oil employment: {pct(nat['formal_share_0'], 1)}% "
             f"in P0 and {pct(nat['formal_share_1'], 1)}% in P1.\n")
    L.append("## 2. Units\n")
    t = dec.sort_values("growth", ascending=False).copy()
    tab = pd.DataFrame({
        "Unit": t["unit"].map(NAME),
        "Growth": t["growth"].map(pct),
        "90% interval": [f"{pct(a)} to {pct(b)}" for a, b in zip(t["growth_lo"], t["growth_hi"])],
        "Within": t["within"].map(pct), "Static": t["static"].map(pct), "Dynamic": t["dynamic"].map(pct),
        "Formalisation": t["formalisation"].map(pct),
        "Formal share P0 (%)": t["formal_share_0"].map(lambda x: pct(x, 1)),
        "Change in formal share (pp)": t["d_formal_share"].map(lambda x: pct(x, 1)),
    })
    L.append(md(tab) + "\n")
    L.append("## 3. Tests\n")
    r41, r42 = t12.loc["P41"], t12.loc["P42"]
    L.append(f"P41. Units with growth above zero: {int(r41['units_positive_growth'])}; of these, with the lower end "
             f"of the 90% interval above zero: {int(r41['eligible_units'])}. Within term larger than reallocation "
             f"(static + dynamic) in {int(r41['within_exceeds_realloc'])} of them (share {r41['share']:.2f}; across "
             f"replications {r41['share_boot_lo']:.2f} to {r41['share_boot_hi']:.2f}). Decision rule: "
             f"{r41['verdict']}.\n")
    bt = TMP / "bootstrap_decomposition.csv"
    if bt.exists():
        r = pd.read_csv(bt)
        m = r.groupby("unit")[["growth", "within", "static", "dynamic", "realloc", "formalisation"]].mean()
        dd = dec.set_index("unit")
        bias = m - dd[m.columns]
        bias.reset_index().to_csv(OUT / "bootstrap_bias.csv", index=False, float_format="%.6f")
        e = dd[(dd["growth"] > 0) & (dd["growth_lo"] > 0)]
        k_bc = int(((2 * e["within"] - m.loc[e.index, "within"]) > (2 * e["realloc"] - m.loc[e.index, "realloc"])).sum())
        shares = []
        for _, g in r.groupby("rep"):
            g = g[(g["growth"] > 0) & g["unit"].map(dd["growth_lo"]).gt(0)]
            shares.append((g["within"] > g["realloc"]).mean())
        shares = np.array(shares)
        L.append(f"Sampling error in ENOE employment biases the terms: the mean of the bootstrap replicates minus the "
                 f"point estimate, averaged over units, is {pct(bias['within'].mean(), 3)} for the within term, "
                 f"{pct(bias['static'].mean(), 3)} for the static term and {pct(bias['dynamic'].mean(), 3)} for the "
                 f"dynamic term (log points a year ×100). With each term corrected for this bias, the within term is "
                 f"larger than reallocation in {k_bc} of the {len(e)} eligible units. Across replications the share is "
                 f"below one third in {100 * (shares < 1 / 3).mean():.0f}% of them and at least two thirds in "
                 f"{100 * (shares >= 2 / 3).mean():.0f}%; the replicates contain the sampling error twice, so this "
                 f"overstates the variability of the verdict.\n")
    L.append(f"P42. Spearman correlation between productivity growth and the change in the formal share, 31 units: "
             f"{r42['rho']:.2f} (90% interval {r42['lo']:.2f} to {r42['hi']:.2f}); partial on initial log "
             f"productivity {r42['partial_rho']:.2f} ({r42['partial_lo']:.2f} to {r42['partial_hi']:.2f}). "
             f"Decision rule: {r42['verdict']}.\n")
    L.append(f"Both variables use ENOE employment. With growth estimated on one half of the primary sampling units and "
             f"the change in the formal share on the other (halves fixed by a hash of the PSU code, each calibrated to "
             f"state population), ρ = {r42['split_rho_a']:.2f} and {r42['split_rho_b']:.2f}; within the same half, "
             f"{r42['same_half_rho_a']:.2f} and {r42['same_half_rho_b']:.2f}. The median correlation of the bootstrap "
             f"errors of the two variables within a unit is {r42['sampling_err_corr_median']:.2f} (check added after "
             f"the plan, D-067).\n")
    L.append(f"P43. Slope of the change in the log product wage on the change in log value added per hour, "
             f"{int(t3['cells'])} unit × group cells ({int(t3['cells_dropped_n<100'])} dropped with fewer than 100 "
             f"respondents in a period), unit and group fixed effects, weighted by initial employment: "
             f"{t3['slope_uncorrected']:.3f} (90% interval {t3['slope_uncorrected_lo']:.3f} to "
             f"{t3['slope_uncorrected_hi']:.3f}); reliability of the regressor {t3['reliability']:.2f}; corrected "
             f"slope {t3['slope']:.3f} (90% interval {t3['lo']:.3f} to {t3['hi']:.3f}). Unweighted, uncorrected: "
             f"{t3['slope_unweighted_uncorrected']:.3f}; without the non-response adjustment, uncorrected: "
             f"{t3['slope_no_nonresponse_adjustment_uncorrected']:.3f}. Decision rule: {t3['verdict']}.\n")
    L.append("## 4. Robustness\n")
    rb = pd.DataFrame({
        "Specification": rob["specification"], "Units": rob["units"], "Units with growth > 0": rob["units_positive"],
        "P41: share within > reallocation": rob["p41_share_within_exceeds"].map(
            lambda x: "" if pd.isna(x) else f"{x:.2f}"),
        "P41 eligible": rob["p41_eligible"].map(lambda x: "" if pd.isna(x) else int(x)),
        "Median growth": rob["median_growth"].map(pct), "Median within": rob["median_within"].map(pct),
        "Median reallocation": rob["median_realloc"].map(pct),
        "Median formalisation": rob["median_formalisation"].map(pct),
        "P42 ρ": rob["p42_rho"].map(lambda x: "" if pd.isna(x) else f"{x:.2f}"),
        "P42 interval": [("" if pd.isna(a) else f"{a:.2f} to {b:.2f}") for a, b in zip(rob["p42_lo"], rob["p42_hi"])],
        "Capped cells": rob["capped_cells"]})
    L.append(md(rb) + "\n")
    L.append("In the 32-state specification no bootstrap is run, and all units with positive growth are counted for "
             "P41. Capped cells: unit × group × period cells in which the informal value added allocated from MEITEF "
             "exceeded PIBE value added and was set equal to it.\n")
    L.append("## 5. Contributions to national growth\n")
    con["Unit"] = con["unit"].map(NAME)
    for lab, sub in (("largest positive", con.nlargest(15, "total")), ("largest negative", con.nsmallest(15, "total"))):
        L.append(f"*Fifteen {lab} unit × group contributions (within + static + dynamic)*\n")
        L.append(md(pd.DataFrame({"Unit": sub["Unit"], "Group": sub["group"], "Contribution": sub["total"].map(
            lambda x: pct(x, 3)), "Within": sub["within"].map(lambda x: pct(x, 3)),
            "Reallocation": (sub["static"] + sub["dynamic"]).map(lambda x: pct(x, 3)),
            "Employment share P0 (%)": sub["emp_share_0"].map(lambda x: pct(x, 2)),
            "Employment share P1 (%)": sub["emp_share_1"].map(lambda x: pct(x, 2)),
            "Group productivity growth": sub["prod_growth"].map(pct)})) + "\n")
    L.append("## 6. Fastest and slowest units: groups behind the terms\n")
    det["L0"], det["L1"] = det["emp0"], det["emp1"]
    for u in list(dec.nlargest(6, "growth")["unit"]) + list(dec.nsmallest(6, "growth")["unit"]):
        x = det[det["unit"] == u].copy()
        s0, s1 = x["L0"] / x["L0"].sum(), x["L1"] / x["L1"].sum()
        p0, p1 = x["va0"] / x["L0"], x["va1"] / x["L1"]
        P0, P1 = x["va0"].sum() / x["L0"].sum(), x["va1"].sum() / x["L1"].sum()
        k = np.log(P1 / P0) / 12 / (P1 - P0)
        x["within"] = s0 * (p1 - p0) * k
        x["realloc"] = (p0 * (s1 - s0) + (p1 - p0) * (s1 - s0)) * k
        w = x.nlargest(2, "within")
        wneg = x.nsmallest(2, "within")
        r = x.nlargest(2, "realloc")
        L.append(f"- {NAME[u]} (growth {pct(np.log(P1 / P0) / 12)}): largest positive within terms "
                 + "; ".join(f"{g} {pct(v, 2)}" for g, v in zip(w["group"], w["within"]))
                 + ". Largest negative within terms " + "; ".join(f"{g} {pct(v, 2)}" for g, v in zip(wneg["group"],
                                                                                              wneg["within"]))
                 + ". Largest reallocation terms " + "; ".join(f"{g} {pct(v, 2)}" for g, v in zip(r["group"],
                                                                                             r["realloc"])) + ".")
    L.append("")
    L.append("## 7. Named cases\n")
    _p = importlib.util.spec_from_file_location("panel97", HERE.parent / "02_panel.py")
    pm = importlib.util.module_from_spec(_p)
    _p.loader.exec_module(pm)
    oil = pm.pibe_activity("21p")
    oil["period"] = oil["year"].map(est.period_of)
    oil = oil[oil["period"].isin(["P0", "P1"])].groupby(["period", "ent"])["va_k"].mean()
    psu = pd.read_parquet(TMP / "psu_cells.parquet", columns=["year", "q", "ent", "act", "w"])
    psu = psu[psu["act"] == "OIL"]
    psu["period"] = psu["year"].map(est.period_of)
    ow = psu[psu["period"].isin(["P0", "P1"])].groupby(["period", "ent"])["w"].sum() / 12
    rows = []
    for case, ents in est.CASES.items():
        for u in ents:
            x = det[det["unit"] == u].copy()
            a0, a1 = x["emp0"].sum(), x["emp1"].sum()
            g = np.log((x["va1"].sum() / a1) / (x["va0"].sum() / a0)) / 12
            v0, v1 = x["va0"].sum() + oil.get(("P0", u), 0), x["va1"].sum() + oil.get(("P1", u), 0)
            l0, l1 = a0 + ow.get(("P0", u), 0), a1 + ow.get(("P1", u), 0)
            x["dshare"] = x["emp1"] / a1 - x["emp0"] / a0
            top = x.nlargest(1, "dshare").iloc[0]
            gp = np.log((top["va1"] / top["emp1"]) / (top["va0"] / top["emp0"])) / 12
            rows.append({"Case": case, "Unit": NAME[u], "Non-oil productivity growth": pct(g),
                         "Productivity growth including oil": pct(np.log((v1 / l1) / (v0 / l0)) / 12),
                         "Employment growth": pct(np.log(a1 / a0) / 12),
                         "Group with the largest gain in employment share": top["group"],
                         "Its share P0 → P1 (%)": f"{pct(top['emp0'] / a0, 1)} → {pct(top['emp1'] / a1, 1)}",
                         "Its productivity growth": pct(gp)})
    L.append(md(pd.DataFrame(rows)) + "\n")
    L.append("Log points a year ×100, 2005–2007 to 2017–2019. Productivity including oil adds PIBE oil-mining value "
             "added and ENOE workers in oil and gas extraction (ENOE code 2110).\n")
    L.append("## 8. 2017–2019 to 2022–2024 (descriptive)\n")
    L.append("ENOE weights for 2022–2024 are based on the 2020 census and those for 2017–2019 on projections from the "
             "2010 census, so employment, and hence productivity, are not on the same basis in the two periods "
             "(OQ-79).\n")
    L.append(f"Median unit growth {pct(d2['growth'].median())}; units with positive growth {int((d2['growth'] > 0).sum())} "
             f"of {len(d2)}; median within {pct(d2['within'].median())}, median reallocation "
             f"{pct(d2['realloc'].median())}.\n")
    L.append("## 9. Data checks\n")
    L.append(md(checks.assign(value=checks["value"].map(lambda v: f"{v:.4g}"))) + "\n")
    (OUT / "results.md").write_text("\n".join(L), encoding="utf-8")
    print("written", OUT / "results.md")


if __name__ == "__main__":
    main()
