"""How good are the ILO modelled estimates for a decomposition? (D-026)

    python empirics/code/carib_lp/04_validate.py

For every country with modelled employment and at least two usable survey
years, take a chain of non-overlapping survey-year pairs at least MIN_GAP
years apart, and decompose productivity growth over each pair twice, with the
same value added: once with survey employment, once with modelled employment.
If the modelled series reproduces the survey-based within and structural
terms between survey years, it can be used for periods whose endpoints are at
or near survey years; between anchors it is interpolation and is not trusted
on its own.

Outputs: empirics/output/carib_lp/validation/{pairs_A,pairs_B,summary}.csv, validation.md
"""
import numpy as np
import pandas as pd

from config import COUNTRIES, OUTPUT, PROCESSED
from decompose import GRIDS, decompose, va_at_prices

MIN_GAP = 4
OUT = OUTPUT / "validation"


def load():
    p = pd.read_csv(PROCESSED / "panel_7sector.csv")
    va = p.dropna(subset=["va_cur_usd", "va_k2020usd"]).set_index(["iso3", "year", "sector"])[["va_cur_usd", "va_k2020usd"]]
    e5 = pd.read_csv(PROCESSED / "emp_5sector.csv")
    emp = {
        ("A", "model"): p.dropna(subset=["emp_model"]).set_index(["iso3", "year", "sector"])["emp_model"],
        ("A", "survey"): p.dropna(subset=["emp_survey"]).set_index(["iso3", "year", "sector"])["emp_survey"],
        ("B", "model"): e5[e5.series == "model"].set_index(["iso3", "year", "sector"])["emp"],
        ("B", "survey"): e5[e5.series == "survey"].set_index(["iso3", "year", "sector"])["emp"],
    }
    return va, emp


def years_of(s, iso):
    return sorted(s.loc[iso].index.get_level_values(0).unique()) if iso in s.index.get_level_values(0) else []


def chain(years, min_gap=MIN_GAP):
    out, start = [], None
    for y in years:
        if start is None:
            start = y
        elif y - start >= min_gap:
            out.append((start, y))
            start = y
    return out


def run_pairs(va, emp, grid):
    rows = []
    m, s = emp[(grid, "model")], emp[(grid, "survey")]
    va_years = set(va.index.get_level_values(1))
    for iso in COUNTRIES:
        my = set(years_of(m, iso))
        sy = [y for y in years_of(s, iso) if y in my and y in va_years]
        for t0, T in chain(sy):
            y = va_at_prices(va, iso, t0, T, "initial", GRIDS[grid])
            r_s = decompose(y, s.loc[(iso, t0)], s.loc[(iso, T)], T - t0)
            r_m = decompose(y, m.loc[(iso, t0)], m.loc[(iso, T)], T - t0)
            if r_s is None or r_m is None:
                continue
            row = {"iso3": iso, "t0": t0, "T": T, "years": T - t0}
            for k in ["growth_pp", "within_pp", "struct_pp"]:
                row[f"{k}_survey"], row[f"{k}_model"] = r_s[k], r_m[k]
            rows.append(row)
    return pd.DataFrame(rows)


def summarize(df, grid):
    if df.empty:
        return {}
    d = df["struct_pp_model"] - df["struct_pp_survey"]
    same_sign = (np.sign(df["struct_pp_model"]) == np.sign(df["struct_pp_survey"])) | (df[["struct_pp_model", "struct_pp_survey"]].abs().max(axis=1) < 0.25)
    return {
        "grid": grid, "pairs": len(df), "countries": df["iso3"].nunique(),
        "corr_struct": df["struct_pp_model"].corr(df["struct_pp_survey"]),
        "corr_within": df["within_pp_model"].corr(df["within_pp_survey"]),
        "mad_struct_pp": d.abs().mean(), "median_ad_struct_pp": d.abs().median(),
        "max_ad_struct_pp": d.abs().max(),
        "share_within_0p5pp": (d.abs() <= 0.5).mean(),
        "sign_agree_share": same_sign.mean(),
        "mean_bias_struct_pp": d.mean(),
        "sd_struct_survey": df["struct_pp_survey"].std(), "sd_struct_model": df["struct_pp_model"].std(),
    }


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    va, emp = load()
    summ, tabs = [], {}
    for grid in ["A", "B"]:
        df = run_pairs(va, emp, grid)
        df.to_csv(OUT / f"pairs_{grid}.csv", index=False)
        tabs[grid] = df
        summ.append(summarize(df, grid))
    summ = pd.DataFrame(summ)
    summ.to_csv(OUT / "summary.csv", index=False)
    write_md(summ, tabs)
    print(summ.T)
    for g, df in tabs.items():
        print(f"\nGrid {g}")
        print(df[["iso3", "t0", "T", "struct_pp_survey", "struct_pp_model", "within_pp_survey", "within_pp_model"]].round(2).to_string())


def write_md(summ, tabs):
    L = ["# Validation of ILO modelled employment against survey employment", "",
         "Generated by `empirics/code/carib_lp/04_validate.py`. Do not edit by hand.", "",
         f"Each row decomposes labour-productivity growth between two usable survey years (at least {MIN_GAP} years apart, "
         "non-overlapping) with the same value added (initial-year prices) and two employment series. Terms are "
         "contributions to annual growth in percentage points.", "",
         "## Summary", "",
         "| Grid | Pairs | Countries | Corr. structural term | Corr. within term | Mean abs. diff. structural (pp/yr) | Median | Max | Share within 0.5 pp | Same sign | Mean bias (model − survey) |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in summ.iterrows():
        L.append(f"| {r['grid']} | {r['pairs']} | {r['countries']} | {r['corr_struct']:.2f} | {r['corr_within']:.2f} | "
                 f"{r['mad_struct_pp']:.2f} | {r['median_ad_struct_pp']:.2f} | {r['max_ad_struct_pp']:.2f} | "
                 f"{r['share_within_0p5pp']:.0%} | {r['sign_agree_share']:.0%} | {r['mean_bias_struct_pp']:+.2f} |")
    for g, df in tabs.items():
        L += ["", f"## Grid {g}: pairs", "",
              "| Country | Period | Growth survey | Growth model | Within survey | Within model | Structural survey | Structural model |",
              "|---|---|---|---|---|---|---|---|"]
        for _, r in df.iterrows():
            L.append(f"| {COUNTRIES[r['iso3']][1]} | {r['t0']}–{r['T']} | {r['growth_pp_survey']:.2f} | {r['growth_pp_model']:.2f} | "
                     f"{r['within_pp_survey']:.2f} | {r['within_pp_model']:.2f} | {r['struct_pp_survey']:.2f} | {r['struct_pp_model']:.2f} |")
    (OUT / "validation.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
